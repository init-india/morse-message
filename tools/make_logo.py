"""Builds the Morse Message logo: 'sms' (lowercase) on line 1, dot-dash-dot on line 2.
Outputs the Android adaptive-icon foreground (vector, 108dp canvas) and a 512px store icon.

Usage:
    python3 tools/make_logo.py app/src/main/res/drawable/ic_launcher_foreground.xml icon.svg
    rsvg-convert -w 512 -h 512 icon.svg -o fastlane/metadata/android/en-US/images/icon.png
"""
import sys
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.pens.boundsPen import BoundsPen

FONT = "/usr/share/fonts/opentype/inter/Inter-Bold.otf"   # Inter: SIL Open Font License
TEXT = "sms"
NAVY, BRASS = "#12263A", "#F4B942"

font = TTFont(FONT)
gs, cmap = font.getGlyphSet(), font.getBestCmap()
names = [cmap[ord(c)] for c in TEXT]
hmtx = font["hmtx"]

# Measure the word (font units, y up)
bp = BoundsPen(gs); x = 0
for n in names:
    gs[n].draw(TransformPen(bp, (1, 0, 0, 1, x, 0))); x += hmtx[n][0]
xmin, ymin, xmax, ymax = bp.bounds

# Layout in the 108x108 canvas (safe zone: circle r=33 around 54,54)
TEXT_W = 46.0                       # word width in dp
s = TEXT_W / (xmax - xmin)
text_h = (ymax - ymin) * s
gap, dot_r, dash_w = 7.0, 4.2, 17.0
group_h = text_h + gap + 2 * dot_r
top = 54 - group_h / 2
baseline = top + ymax * s           # y (down) of font baseline
left = 54 - TEXT_W / 2 - xmin * s

pen = SVGPathPen(gs, ntos=lambda v: f"{v:.2f}".rstrip("0").rstrip("."))
x = 0
for n in names:
    gs[n].draw(TransformPen(pen, (s, 0, 0, -s, left + x * s, baseline))); x += hmtx[n][0]
text_path = pen.getCommands()

cy = top + text_h + gap + dot_r     # centre line of the dot-dash-dot
seg_gap = 5.0
total = 2 * dot_r * 2 + dash_w + 2 * seg_gap
x0 = 54 - total / 2
d1 = (x0 + dot_r, cy)
dash = (x0 + 2 * dot_r + seg_gap, cy - dot_r, x0 + 2 * dot_r + seg_gap + dash_w, cy + dot_r)
d2 = (dash[2] + seg_gap + dot_r, cy)

def circle(cx, cy, r):
    return f"M{cx - r:.2f},{cy:.2f}a{r:.2f},{r:.2f} 0,1 1,{2*r:.2f} 0a{r:.2f},{r:.2f} 0,1 1,{-2*r:.2f} 0z"
def pill(x1, y1, x2, y2):
    r = (y2 - y1) / 2
    return (f"M{x1 + r:.2f},{y1:.2f}h{(x2 - x1) - 2*r:.2f}a{r:.2f},{r:.2f} 0,0 1,0 {2*r:.2f}"
            f"h{-((x2 - x1) - 2*r):.2f}a{r:.2f},{r:.2f} 0,0 1,0 {-2*r:.2f}z")
morse_path = circle(*d1, dot_r) + pill(*dash) + circle(*d2, dot_r)

vector = f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Morse Message logo: "sms" over dot-dash-dot, centred in the 108dp adaptive-icon canvas
     (inside the 66dp safe zone). "sms" outlines from Inter Bold (SIL Open Font License).
     Generated by tools/make_logo.py. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <path
        android:fillColor="@color/launcher_foreground"
        android:pathData="{text_path}" />
    <path
        android:fillColor="@color/launcher_foreground"
        android:pathData="{morse_path}" />
</vector>
'''
open(sys.argv[1], "w").write(vector)

# Store icon: full-bleed square, same artwork scaled up a little (no adaptive-icon mask there)
svg = f'''<svg xmlns="http://www.w3.org/2000/svg" width="512" height="512" viewBox="10 10 88 88">
<rect x="0" y="0" width="108" height="108" fill="{NAVY}"/>
<path fill="{BRASS}" d="{text_path}"/><path fill="{BRASS}" d="{morse_path}"/></svg>'''
open(sys.argv[2], "w").write(svg)
print(f"text {text_h:.1f}dp high, group {top:.1f}..{top + group_h:.1f}, dots y={cy:.1f}")
